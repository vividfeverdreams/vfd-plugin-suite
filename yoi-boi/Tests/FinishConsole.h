inline bool finishCandidates (const juce::File& folder)
{
    if (!folder.createDirectory()) return false;
    const juce::StringArray wanted { "Squeaky Clean", "Bubble Trouble", "Low Talker", "Basement Answer", "Riser Chirp", "Space Bass Cadet", "Glitch Mouth" };
    for (const auto& source : allFactoryPresets())
    {
        if (!wanted.contains (source.name)) continue;
        YoiBoiProcessor synth (folder.getChildFile ("unused-presets"));
        synth.makeEditorCallbacks().loadPreset (source.presetId);
        juce::MemoryBlock state; synth.getStateInformation (state);
        const auto tree = juce::ValueTree::fromXml (*juce::AudioProcessor::getXmlFromBinary (state.getData(), static_cast<int> (state.getSize())));
        const auto current = fromValueTree (tree.getChildWithName ("YoiBoiPatch"));
        if (!current) return false;
        for (float amount : {.05f, .25f, .65f}) for (float balance : {.1f, .35f, .75f})
        {
            auto p = *current; p.finish = amount; p.subBalance = balance;
            voicePatch (p, true); const auto audio = renderVoicingPhrase (p);
            const auto name = p.name + "__" + juce::String (amount,2) + "__" + juce::String (balance,2) + ".wav";
            auto fileStream = folder.getChildFile (name).createOutputStream();
            if (!fileStream) return false;
            fileStream->setPosition (0); if (fileStream->truncate().failed()) return false;
            std::unique_ptr<juce::OutputStream> stream = std::move (fileStream);
            juce::WavAudioFormat format; auto writer = format.createWriterFor (stream, juce::AudioFormatWriterOptions{}.withSampleRate (48000).withNumChannels (2).withBitsPerSample (24));
            juce::AudioBuffer<float> buffer (2, static_cast<int> (audio.left.size()));
            buffer.copyFrom (0,0,audio.left.data(),buffer.getNumSamples()); buffer.copyFrom (1,0,audio.right.data(),buffer.getNumSamples());
            if (!writer || !writer->writeFromAudioSampleBuffer (buffer,0,buffer.getNumSamples())) return false;
            std::cout << name << '\t' << audio.lufs << '\t' << p.loudnessTrim << std::endl;
        }
    }
    return true;
}
