inline double truePeak4x (const juce::AudioBuffer<float>& audio)
{
    // 64-tap Blackman-windowed sinc, four reconstruction phases. Offline only.
    std::array<std::array<double, 64>, 4> coefficients {};
    for (int phase = 0; phase < 4; ++phase)
    {
        double sum = 0;
        for (int tap = 0; tap < 64; ++tap)
        {
            const double t = tap - 31.0 - phase * .25;
            const double sinc = std::abs (t) < 1e-12 ? 1 : std::sin (juce::MathConstants<double>::pi * t) / (juce::MathConstants<double>::pi * t);
            const double window = .42 - .5 * std::cos (2 * juce::MathConstants<double>::pi * tap / 63)
                                   + .08 * std::cos (4 * juce::MathConstants<double>::pi * tap / 63);
            coefficients[static_cast<std::size_t> (phase)][static_cast<std::size_t> (tap)] = sinc * window;
            sum += sinc * window;
        }
        for (auto& x : coefficients[static_cast<std::size_t> (phase)]) x /= sum;
    }
    double peak = 0;
    for (int c = 0; c < audio.getNumChannels(); ++c)
        for (int i = 0; i < audio.getNumSamples(); ++i)
        {
            peak = std::max (peak, std::abs (static_cast<double> (audio.getSample (c, i))));
            for (const auto& phase : coefficients)
            {
                double x = 0;
                for (int tap = 0; tap < 64; ++tap)
                {
                    const int index = i + tap - 31;
                    if (index >= 0 && index < audio.getNumSamples()) x += audio.getSample (c, index) * phase[static_cast<std::size_t> (tap)];
                }
                peak = std::max (peak, std::abs (x));
            }
        }
    return peak > 0 ? 20 * std::log10 (peak) : -120;
}
inline bool measureWavs (const juce::File& folder)
{
    juce::AudioFormatManager formats; formats.registerBasicFormats();
    auto files = folder.findChildFiles (juce::File::findFiles, false, "*.wav"); files.sort();
    bool ok = !files.isEmpty();
    std::cout << "file\tLUFS_I\ttrue_peak_dBTP\n";
    for (const auto& file : files)
    {
        if (file.getFileName().startsWith ("YOI-BOI-factory-tour")) continue;
        std::unique_ptr<juce::AudioFormatReader> reader (formats.createReaderFor (file));
        if (!reader || reader->sampleRate != 48000 || reader->numChannels != 2) return false;
        juce::AudioBuffer<float> audio (2, static_cast<int> (reader->lengthInSamples));
        if (!reader->read (&audio, 0, audio.getNumSamples(), 0, true, true)) return false;
        dsp::IntegratedLoudness meter;
        for (int i = 0; i < audio.getNumSamples(); ++i) meter.push (audio.getSample (0, i), audio.getSample (1, i));
        std::cout << file.getFileName() << '\t' << std::fixed << std::setprecision (4) << meter.integrated() << '\t' << truePeak4x (audio) << '\n';
    }
    return ok;
}
inline bool bakeFinish (const juce::File& destination)
{
    juce::String text = "#pragma once\n#include <array>\nnamespace yoiboi {\n// Generated by --bake-finish: BS.1770 gated -10 LUFS, standard 140 BPM phrase.\ninline constexpr std::array<float, 87> factoryFinishTrim {\n";
    juce::String amountText, balanceText;
    std::cout << "preset\ttrim_dB\tLUFS_I\tpeak\tCPU_seconds\n";
    bool ok = true;
    for (auto p : allFactoryPresets())
    {
        voicePatch (p, true);
        PhraseRender result;
        for (int iteration = 0; iteration < 4; ++iteration)
        {
            result = renderVoicingPhrase (p);
            if (std::abs (result.lufs + 10) < .02) break;
            p.loudnessTrim += static_cast<float> (std::clamp (-10.0 - result.lufs, -2.0, 2.0));
        }
        text += "    " + juce::String (p.loudnessTrim, 5) + "f, // " + p.name + "\n";
        amountText += "    " + juce::String (p.finish, 3) + "f, // " + p.name + "\n";
        balanceText += "    " + juce::String (p.subBalance, 3) + "f, // " + p.name + "\n";
        std::cout << p.name << '\t' << p.loudnessTrim << '\t' << result.lufs << '\t' << result.peak << '\t' << result.seconds << std::endl;
        ok = ok && std::abs (result.lufs + 10) <= 1 && result.peak <= .89125094;
    }
    text += "};\ninline constexpr std::array<float, 87> factoryFinishAmount {\n" + amountText + "};\ninline constexpr std::array<float, 87> factorySubBalance {\n" + balanceText + "};\n}\n";
    return destination.replaceWithText (text) && ok;
}
inline bool rollStats (int count)
{
    int passed = 0;
    double low = 100, high = -100; float peak = 0;
    std::cout << "seed\tfamily\tLUFS_I\tpeak\ttrim_dB\trender_seconds\ttrue_peak_dBTP\n";
    // Match a fresh processor, including its authored velocity performance settings.
    const auto base = allFactoryPresets()[12];
    for (int i = 0; i < count; ++i)
    {
        // Consecutive independent seeds, all four families, default player locks.
        auto p = newYoi (base, defaultPatchLocks(), static_cast<std::uint64_t> (i + 1));
        voiceGeneratedPatch (p);
        const auto result = renderVoicingPhrase (p);
        const float* data[] {result.left.data(), result.right.data()};
        juce::AudioBuffer<float> reconstructed (const_cast<float**> (data), 2, static_cast<int> (result.left.size()));
        const double tp = truePeak4x (reconstructed);
        const bool ok = std::isfinite (result.lufs) && std::abs (result.lufs + 10) <= 2 && tp <= -1 && result.peak <= .89125094;
        passed += ok ? 1 : 0;
        low = std::min (low, result.lufs); high = std::max (high, result.lufs); peak = std::max (peak, result.peak);
        std::cout << i + 1 << '\t' << familyName (p.family) << '\t' << result.lufs << '\t' << result.peak << '\t' << p.loudnessTrim << '\t' << result.seconds << '\t' << tp << (ok ? "" : "\tFAIL") << std::endl;
    }
    std::cout << "ROLLS " << passed << '/' << count << " pass, range=" << low << ".." << high << " LUFS; peak=" << peak << '\n';
    return passed == count;
}
