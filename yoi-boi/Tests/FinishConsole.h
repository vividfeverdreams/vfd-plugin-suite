inline bool checkFinishDSP()
{
    int checks = 0, passed = 0;
    const auto check = [&] (bool ok, const juce::String& label)
    { ++checks; passed += ok ? 1 : 0; std::cout << (ok ? "PASS " : "FAIL ") << label << std::endl; };
    dsp::IntegratedLoudness meter, silent;
    for (int i = 0; i < 48000 * 6; ++i)
    {
        const float x = i < 144000 ? .1f * static_cast<float> (std::sin (2 * juce::MathConstants<double>::pi * 1000 * i / 48000)) : 0;
        meter.push (x, x); silent.push (0, 0);
    }
    check (std::abs (meter.integrated() + 20) < .25 && silent.integrated() == -120, "BS.1770 reference + gates: " + juce::String (meter.integrated(), 4));
    for (int engine = 1; engine <= 4; ++engine)
    {
        auto p = makeDefaultPatch(); p.soundEngine = engine;
        const auto result = renderVoicingPhrase (p); bool finite = true;
        for (auto x : result.left) finite = finite && std::isfinite (x);
        check (finite && result.peak > .01f && result.peak <= .875f, "FINISH engine " + juce::String (engine) + " finite/bounded, peak=" + juce::String (result.peak));
    }
    for (const bool modern : { false, true })
    {
        auto voice = std::make_unique<dsp::YoiVoice4>();
        dsp::LatestControls c; c.sub = 1; c.output = 1; c.separateSub = true;
        c.subOnNote = modern; c.lowCutTrack = modern; c.finish = modern ? .45f : 0.f;
        voice->setControls (c); voice->prepare (48000); voice->noteOn (36, 1, 0);
        float previous = 0; int crossings = 0; double dc = 0;
        for (int i = 0; i < 48000; ++i)
        {
            const float x = voice->renderFrame().sub;
            if (i >= 24000) { crossings += x > 0 && previous <= 0; dc += x / 24000; } previous = x;
        }
        check (std::abs (crossings - (modern ? 32.7032 : 16.3516)) < 1.1 && std::abs (dc) < .004,
               juce::String (modern ? "Sub on C2" : "Legacy sub octave down") + ": crossings/0.5s=" + juce::String (crossings) + ", DC=" + juce::String (dc, 6));
        if (modern)
        {
            voice->noteOn (60, 1, 100); voice->setLowestHeldNote (36);
            for (int i = 0; i < 48000; ++i) voice->renderFrame();
            check (std::abs (voice->trackedCutoff() - 92.4986) < .1, "Lowest held C2 -> sqrt(2)*f0 cutoff below higher last note");
            voice->setLowestHeldNote (48);
            for (int i = 0; i < 4800; ++i) voice->renderFrame();
            const float middle = voice->trackedCutoff();
            for (int i = 0; i < 48000; ++i) voice->renderFrame();
            check (middle > 92.5f && middle < 185 && std::abs (voice->trackedCutoff() - 184.997) < .1, "Low cut glides after releasing lowest note");
        }
    }
    YoiBoiProcessor processor (juce::File::getSpecialLocation (juce::File::tempDirectory).getChildFile ("unused-finish-presets"));
    check (processor.getLatencySamples() == dsp::YoiVoice::latencySamples() && std::abs (processor.parameters().getRawParameterValue ("output_db")->load()) < .0001f, "Fresh processor: unity output, 0.2.5 latency reporting");
    auto callbacks = processor.makeEditorCallbacks(); bool backendUnlocked = true;
    for (const auto* id : {"finish", "sub_on_note", "low_cut_track", "loudness_trim", "sub_balance"})
    { callbacks.setParameterLock (id, true); backendUnlocked = backendUnlocked && !callbacks.isParameterLocked (id); }
    check (backendUnlocked && processor.parameters().getParameter ("finish")->getParameterIndex() == 42
           && processor.parameters().getParameter ("sub_balance")->getParameterIndex() == 46,
           "Five backend controls append at 42..46 and stay outside randomization locks");
    auto layout = processor.getBusesLayout(); layout.outputBuses.getReference (1) = juce::AudioChannelSet::stereo();
    const bool route = processor.setBusesLayout (layout); processor.prepareToPlay (48000, 256);
    juce::AudioBuffer<float> block (4, 256); double subEnergy = 0; bool mono = true, finite = true;
    for (int b = 0; b < 100; ++b)
    {
        juce::MidiBuffer midi; if (b == 0) midi.addEvent (juce::MidiMessage::noteOn (1, 36, (juce::uint8)112), 0);
        processor.processBlock (block, midi);
        for (int i = 0; i < 256; ++i)
        {
            subEnergy += block.getSample (2, i) * block.getSample (2, i);
            mono = mono && block.getSample (2, i) == block.getSample (3, i);
            for (int c = 0; c < 4; ++c) finite = finite && std::isfinite (block.getSample (c, i)) && std::abs (block.getSample (c, i)) <= .875f;
        }
    }
    check (route && mono && finite && subEnergy > 1, "Separate Sub bus: audible mono, finite, ceiling-safe"); processor.releaseResources();
    for (int preset : {2, 6, 12, 24})
    {
        YoiBoiProcessor synth (juce::File::getSpecialLocation (juce::File::tempDirectory).getChildFile ("unused-finish-probe"));
        synth.makeEditorCallbacks().loadPreset ("factory:" + juce::String (preset));
        juce::MemoryBlock state; synth.getStateInformation (state);
        const auto tree = juce::ValueTree::fromXml (*juce::AudioProcessor::getXmlFromBinary (state.getData(), static_cast<int> (state.getSize())));
        const auto p = fromValueTree (tree.getChildWithName ("YoiBoiPatch"));
        if (!p) return false;
        const auto reference = renderVoicingPhrase (*p);
        struct Head final : juce::AudioPlayHead
        {
            int sample = 0;
            juce::Optional<PositionInfo> getPosition() const override
            { PositionInfo p; p.setBpm (140); p.setIsPlaying (true); p.setPpqPosition (sample / 48000.0 * 140 / 60); return p; }
        } head;
        synth.setPlayHead (&head); synth.prepareToPlay (48000, 256);
        dsp::IntegratedLoudness actual; double error = 0;
        for (int start = 0; start < 144000; start += 256)
        {
            const int count = std::min (256, 144000 - start); juce::AudioBuffer<float> audio (2, count); juce::MidiBuffer midi;
            constexpr int on[] {0,27360,41280,61440}, off[] {18240,36960,51360,89280}, pitch[] {43,43,46,43};
            for (int n = 0; n < 4; ++n)
            {
                if (on[n] >= start && on[n] < start + count) midi.addEvent (juce::MidiMessage::noteOn (1, pitch[n], (juce::uint8)112), on[n] - start);
                if (off[n] >= start && off[n] < start + count) midi.addEvent (juce::MidiMessage::noteOff (1, pitch[n]), off[n] - start);
            }
            const int sweep = static_cast<int> (64 + 63 * std::sin (start / 48000.0 * 6));
            midi.addEvent (juce::MidiMessage::controllerEvent (1, 1, sweep), 0); midi.addEvent (juce::MidiMessage::channelPressureChange (1, 127 - sweep), 0);
            head.sample = start; synth.processBlock (audio, midi);
            for (int i = 0; i < count; ++i)
            { actual.push (audio.getSample (0,i), audio.getSample (1,i)); error = std::max (error, std::abs (static_cast<double> (audio.getSample (0,i)) - reference.left[static_cast<std::size_t> (start + i)])); }
        }
        synth.releaseResources(); synth.setPlayHead (nullptr);
        check (std::abs (actual.integrated() - reference.lufs) < .2,
               "Voicing/processor parity " + p->name + ": " + juce::String (reference.lufs, 3) + "/" + juce::String (actual.integrated(), 3) + " LUFS; trim=" + juce::String (p->loudnessTrim) + "; max=" + juce::String (error));
    }
    auto patch = toValueTree (makeDefaultPatch());
    for (const auto* id : {"finish", "loudnessTrim", "subOnNote", "lowCutTrack", "subBalance"}) patch.removeProperty (id, nullptr);
    const auto old = fromValueTree (patch);
    check (old && old->finish == 0 && old->loudnessTrim == 0 && std::abs (old->subBalance - 1.f) < 1e-6f && !old->subOnNote && !old->lowCutTrack, "Old XML file: FINISH off, trim 0, octave down, fixed low cut");
    const auto subRms = [] (int pitch)
    {
        auto v = std::make_unique<dsp::YoiVoice4>(); dsp::LatestControls c;
        c.finish = .25f; c.sub = c.output = 1; c.subOnNote = c.separateSub = true;
        v->setControls (c); v->prepare (48000); v->noteOn (pitch, 1, 0);
        double energy = 0;
        for (int i = 0; i < 48000; ++i) { const double x = v->renderFrame().sub; if (i >= 24000) energy += x * x / 24000; }
        return std::sqrt (energy);
    };
    const double infraRatio = subRms (12) / subRms (36);
    check (infraRatio < .13, "Infrasonic 16 Hz sub is attenuated without transposing: " + juce::String (20 * std::log10 (infraRatio), 2) + " dB vs C2");
    dsp::Finisher finish; finish.prepare (192000); finish.set (.45f, 0); finish.reset();
    dsp::HalfbandDecimator d4, d2; d4.prepare(); d2.prepare(); double re = 0, im = 0, energy = 0;
    for (int i = 0; i < 48000 + 4096; ++i)
    {
        float high[4];
        for (int k = 0; k < 4; ++k)
        {
            const double t = (i * 4.0 + k) / 192000;
            high[k] = finish.dc (finish.glue (.95f * static_cast<float> (std::sin (2 * juce::MathConstants<double>::pi * 7000 * t)), 0), 0);
        }
        const float first = d4.process (high[0], high[1]), second = d4.process (high[2], high[3]);
        const auto x = d2.process (first, second);
        if (i >= 4096)
        {
            const double phase = 2 * juce::MathConstants<double>::pi * 3000 * i / 48000;
            re += x * std::cos (phase); im += x * std::sin (phase); energy += x * x;
        }
    }
    const double aliasDb = 20 * std::log10 (std::max (1e-15, 2 * std::hypot (re, im) / 48000));
    check (aliasDb < -85 && energy > 1, "4x GLUE .95-peak/7 kHz: folded 3 kHz bin=" + juce::String (aliasDb, 2) + " dBFS (<-85)");
    std::cout << "FINISH DSP " << passed << '/' << checks << " checks passed\n"; return passed == checks;
}
